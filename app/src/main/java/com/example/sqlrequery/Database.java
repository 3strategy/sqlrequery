package com.example.sqlrequery;

import android.content.Context;

import com.example.sqlrequery.model.Movie;
import com.example.sqlrequery.model.MovieEntity;
import com.example.sqlrequery.model.Student;
import com.example.sqlrequery.model.StudentEntity;
import com.example.sqlrequery.model.WatchingEntity;

import io.requery.Persistable;
import io.requery.android.sqlite.DatabaseSource;
import io.requery.sql.EntityDataStore;

/**
 * Contains the complete database setup and the three insert operations used by the demo.
 *
 * <p>The class is intentionally a small static helper. A production app might introduce an
 * {@code Application}, repository, dependency injection, and background execution; those layers
 * are omitted here so the route from a generated entity to SQLite remains visible.</p>
 */
final class Database {
    /** One store is reused for the life of this small application. */
    private static EntityDataStore<Persistable> data;

    /**
     * Opens the normal Android SQLite database through Requery.
     *
     * <p>{@link DatabaseSource} adapts Android's SQLite APIs to Requery. {@link Models#DEFAULT} is
     * generated from the three {@code @Entity} interfaces and tells Requery which tables to create.
     * Version {@code 1} is the SQLite schema version.</p>
     *
     * @param context any Android context; the application context is retained safely
     * @return the shared store used for inserts and typed queries
     */
    static synchronized EntityDataStore<Persistable> open(Context context) {
        if (data == null) {
            DatabaseSource source = new DatabaseSource(
                    context.getApplicationContext(), Models.DEFAULT, "class-netflix.db", 1);
            // Logcat reveals the SQL generated by the Java operations in this demo.
            source.setLoggingEnabled(true);
            data = new EntityDataStore<>(source.getConfiguration());
        }
        return data;
    }

    /**
     * Inserts the example graph only when the {@code Student} table is empty.
     *
     * <p>The returned generated entities already contain their SQLite IDs, so they can immediately
     * be assigned to the two {@code @ManyToOne} properties of each Watching row.</p>
     *
     * @param data the open Requery store
     */
    static void seedIfEmpty(EntityDataStore<Persistable> data) {
        if (data.count(Student.class).get().value() != 0) return;

        StudentEntity maya = addStudent(data, "Maya");
        StudentEntity noa = addStudent(data, "Noa");
        StudentEntity dana = addStudent(data, "Dana");

        MovieEntity barbie = addMovie(data, "Barbie", "Comedy");
        MovieEntity dune = addMovie(data, "Dune", "Sci-Fi");
        MovieEntity insideOut = addMovie(data, "Inside Out 2", "Animation");

        addWatching(data, maya, barbie, 9);
        addWatching(data, maya, dune, 8);
        addWatching(data, noa, dune, 10);
        addWatching(data, dana, insideOut, 9);
    }

    /**
     * Creates and inserts one Student row.
     *
     * @param data the open Requery store
     * @param name value for the Student {@code name} column
     * @return the inserted generated entity, including its SQLite-assigned ID
     */
    static StudentEntity addStudent(EntityDataStore<Persistable> data, String name) {
        StudentEntity student = new StudentEntity();
        student.setName(name);
        return data.insert(student);
    }

    /**
     * Creates and inserts one Movie row.
     *
     * @param data the open Requery store
     * @param title value for the Movie {@code title} column
     * @param genre value for the Movie {@code genre} column
     * @return the inserted generated entity, including its SQLite-assigned ID
     */
    static MovieEntity addMovie(EntityDataStore<Persistable> data, String title, String genre) {
        MovieEntity movie = new MovieEntity();
        movie.setTitle(title);
        movie.setGenre(genre);
        return data.insert(movie);
    }

    /**
     * Creates and inserts one row in the Watching association table.
     *
     * <p>Assigning entity objects to {@code setStudent} and {@code setMovie} makes Requery write
     * their IDs to the {@code studentId} and {@code movieId} foreign-key columns. The rating belongs
     * to this association, not to either parent entity.</p>
     *
     * @param data the open Requery store
     * @param student an already-inserted Student
     * @param movie an already-inserted Movie
     * @param rating the relationship's 1–10 rating
     */
    static void addWatching(EntityDataStore<Persistable> data,
                            Student student, Movie movie, int rating) {
        WatchingEntity watching = new WatchingEntity();
        watching.setStudent(student);
        watching.setMovie(movie);
        watching.setRating(rating);
        data.insert(watching);
    }

    /** Prevents instances of this utility class. */
    private Database() {}
}
